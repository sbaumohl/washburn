#!/usr/bin/env python3
"""Render washburn.toml into the artifacts consumed by infra/ and deploy/.

Usage:
    scripts/render-config.py [--config washburn.toml] [--out .rendered]
                             [--allow-placeholders]

Stdlib only (tomllib). Exit codes: 0 ok, 1 validation error, 2 missing config
(argparse also exits 2 on a bad flag). See scripts/README.md for the mapping.
"""

