# Raw compose env files cannot represent these; values containing them are refused.
_ENV_FORBIDDEN = set("\\\"'#$`\n\r")
# borg.env is sourced by bash and read by systemd; W6's borg.env contract forbids
# these (single quote added: it breaks an unquoted bash assignment).
_BORG_FORBIDDEN = set("\\\"'$`\n\r")


class ConfigError(Exception):
    """A problem found while building artifacts (after shape validation)."""


@dataclass(frozen=True)
class Entry:
    key: str
    value: Any
    secret: bool = False
    comment: str = ""

    def display(self) -> str:
        if self.secret:
            return f"<secret, len {len(str(self.value))}>"
        if isinstance(self.value, str):
            return self.value if self.value else "(empty)"
        return json.dumps(self.value, sort_keys=True)


@dataclass
class Artifact:
    rel: str  # path relative to --out
    content: str
    kind: str  # "env" | "json" | "text"
    entries: list[Entry] = field(default_factory=list)

    @property
    def secret(self) -> bool:
        return any(e.secret for e in self.entries)


# ---------------------------------------------------------------- validation
_TYPE_NAMES = {bool: "boolean", int: "integer", float: "number", str: "string"}


def _same_scalar_type(expected: Any, actual: Any) -> bool:
    if isinstance(expected, bool):
        return isinstance(actual, bool)
    if isinstance(expected, (int, float)):
        return isinstance(actual, (int, float)) and not isinstance(actual, bool)
    if isinstance(expected, str):
        return isinstance(actual, str)
    return False


def _check_shape(example: dict, cfg: dict, prefix: str, errors: list[str]) -> None:
    """Every field present in the example must be present, non-empty, typed."""
    for key, ex_val in example.items():
        path = f"{prefix}{key}"
        if key not in cfg:
            if path not in OPTIONAL_TABLES:
                errors.append(f"missing required field {path}")
            continue
        co_val = cfg[key]
        if isinstance(ex_val, dict):
            if not isinstance(co_val, dict):
                errors.append(f"{path} must be a table")
            else:
                _check_shape(ex_val, co_val, path + ".", errors)
        elif isinstance(ex_val, list):
            if not isinstance(co_val, list) or not co_val:
                errors.append(f"missing required field {path} (non-empty list)")
        elif not _same_scalar_type(ex_val, co_val):
            errors.append(f"{path} must be a {_TYPE_NAMES[type(ex_val)]}")
        elif isinstance(co_val, str) and not co_val.strip() and path not in EMPTY_ALLOWED:
            errors.append(f"missing required field {path} (empty)")


def _walk_strings(node: Any, path: str) -> Iterator[tuple[str, str]]:
    if isinstance(node, dict):
        for key, value in node.items():
            yield from _walk_strings(value, f"{path}.{key}" if path else key)
    elif isinstance(node, list):
        for i, value in enumerate(node):
            yield from _walk_strings(value, f"{path}[{i}]")
    elif isinstance(node, str):
        yield path, node


def validate(example: dict, cfg: dict, *, allow_placeholders: bool) -> list[str]:
    """Return human-readable problems. Never includes string values."""
    errors: list[str] = []
    _check_shape(example, cfg, "", errors)
    for path, value in _walk_strings(cfg, ""):
        if not allow_placeholders and value.startswith("REPLACE"):
            errors.append(f"{path} still holds a placeholder (REPLACE...)")
        if "\n" in value or "\r" in value:
            errors.append(f"{path} must be a single line")
    return errors


# ---------------------------------------------------------------- rendering
def env_text(header: list[str], entries: list[Entry], *, quoted: bool) -> str:
    """quoted=True: double-quote a value only when it contains whitespace (the
    borg.env contract; both bash and systemd accept that). quoted=False: raw
    KEY=value, which deploy.sh reads without unquoting (compose env files)."""
    lines = [f"# {line}" for line in header]
    for e in entries:
        if e.comment:
            lines.append(f"# {e.comment}")
        value = str(e.value)
        if quoted and any(ch.isspace() for ch in value):
            lines.append(f'{e.key}="{value}"')
        else:
            lines.append(f"{e.key}={value}")
    return "\n".join(lines) + "\n"


def _env_value_problems(path: str, value: str, forbidden: set[str] = _ENV_FORBIDDEN) -> list[str]:
    if value != value.strip():
        return [f"{path} has leading or trailing whitespace"]
    bad = sorted({ch for ch in value if ch in forbidden})
    if bad:
        # Name the field and the characters, never the value.
        return [f"{path} contains characters that env files cannot hold raw: {' '.join(repr(c) for c in bad)}"]
    return []


_BARE_KEY = re.compile(r"[A-Za-z0-9_-]+")
_TOML_ESCAPES = {"\\": "\\\\", '"': '\\"', "\n": "\\n", "\r": "\\r", "\t": "\\t"}


def _toml_string(text: str) -> str:
    out = []
    for ch in text:
        if ch in _TOML_ESCAPES:
            out.append(_TOML_ESCAPES[ch])
        elif ord(ch) < 0x20 or ord(ch) == 0x7F:
            out.append(f"\\u{ord(ch):04x}")
        else:
            out.append(ch)
    return '"' + "".join(out) + '"'


def _toml_key(key: str) -> str:
    return key if _BARE_KEY.fullmatch(key) else _toml_string(key)


def _toml_value(value: Any) -> str:
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, int):
        return str(value)
    if isinstance(value, float):
        if not math.isfinite(value):
            raise ConfigError("cannot serialise a non-finite float")
        return repr(value)
    if isinstance(value, str):
        return _toml_string(value)
    if isinstance(value, list):
        return "[" + ", ".join(_toml_value(v) for v in value) + "]"
    raise ConfigError(f"cannot serialise a {type(value).__name__}")


def dump_toml(data: dict) -> str:
    """Minimal TOML writer for config tables: scalars, string arrays, nested
    tables. Round-trips through tomllib (checked by the tests)."""
    lines: list[str] = []

    def emit(table: dict, header: str | None) -> None:
        if header is not None:
            lines.append(f"[{header}]")
        for key, value in table.items():
            if not isinstance(value, dict):
                lines.append(f"{_toml_key(key)} = {_toml_value(value)}")
        if header is not None:
            lines.append("")
        for key, value in table.items():
            if isinstance(value, dict):
                sub = _toml_key(key) if header is None else f"{header}.{_toml_key(key)}"
                emit(value, sub)

    emit(data, None)
    return "\n".join(lines).rstrip() + "\n"


def _flatten(table: dict, prefix: str = "") -> list[tuple[str, Any]]:
    out: list[tuple[str, Any]] = []
    for key, value in table.items():
        dotted = f"{prefix}.{key}" if prefix else key
        if isinstance(value, dict):
            out += _flatten(value, dotted)
        else:
            out.append((dotted, value))
    return out


def render_role_toml(role: str, cfg: dict) -> Artifact:
    data = {table: cfg[table] for table in ROLE_TOML_TABLES[role]}
    entries = [Entry(path, value, path in SECRET_PATHS) for path, value in _flatten(data)]
    return Artifact(f"config/{role}.toml", dump_toml(data), "toml", entries)


def image_refs(cfg: dict, warnings: list[str]) -> dict[str, str]:
    images = cfg.get("images")
    if images is None:
        warnings.append(
            f"[images] not set: image references use {DEFAULT_IMAGE_REGISTRY}/"
            "washburn-<name>:latest. Add [images] registry and tag before deploying."
        )
        registry, tag = DEFAULT_IMAGE_REGISTRY, "latest"
    else:
        registry, tag = images.get("registry", ""), images.get("tag", "")
        if not registry or not tag:
            raise ConfigError("[images] needs both registry and tag")
        if "OWNER" in registry:
            warnings.append("[images] registry still contains OWNER; set it to your GHCR owner before deploying.")
    registry = registry.rstrip("/")
    return {f"image.{role}": f"{registry}/washburn-{role}:{tag}" for role in IMAGE_ROLES}


def lookup(cfg: dict, derived: dict[str, str], path: str) -> Any:
    """Dotted lookup. Missing optional fields resolve to ""; required ones are
    guaranteed present by validate()."""
    if path in derived:
        return derived[path]
    node: Any = cfg
    for part in path.split("."):
        if not isinstance(node, dict) or part not in node:
            return ""
        node = node[part]
    return node


def _env_entries(cfg: dict, derived: dict[str, str], spec: list[tuple[str, ...]]) -> list[Entry]:
    entries = []
    problems: list[str] = []
    for name, src, *rest in spec:
        comment = rest[0] if rest else ""
        if src is None:
            entries.append(Entry(name, "", False, comment))
            continue
        value = str(lookup(cfg, derived, src))
        problems += _env_value_problems(src, value)
        entries.append(Entry(name, value, src in SECRET_PATHS, comment))
    if problems:
        raise ConfigError("; ".join(problems))
    return entries


def render_tfvars(cfg: dict) -> Artifact:
    vultr, tailscale = cfg["vultr"], cfg["tailscale"]
    values: dict[str, Any] = {
        "vultr_api_key": vultr["api_key"],
        "region": vultr["region"],
        "os_id": vultr["os_id"],
        "ssh_key_ids": list(vultr["ssh_key_ids"]),
        "plans": {role: vultr["plans"][role] for role in ROLES},
        "counts": {"crawler": vultr["counts"]["crawler"]},
        "tailscale_auth_key": tailscale["auth_key"],
        "tailnet": tailscale["tailnet"],
        "public_host": cfg["domain"]["public_host"],
        "enable_vpc": False,
        "project_tag": "washburn",
        "enable_reserved_ip": False,
    }
    entries = [Entry(k, v, k in TFVARS_SECRET_KEYS) for k, v in values.items()]
    content = json.dumps(values, indent=2) + "\n"
    return Artifact("infra/terraform.tfvars.json", content, "json", entries)


def render_role_env(role: str, cfg: dict, derived: dict[str, str]) -> Artifact:
    entries = _env_entries(cfg, derived, ROLE_ENV[role])
    return Artifact(
        f"deploy/compose/{role}.env",
        env_text(ENV_HEADER, entries, quoted=False),
        "env",
        entries,
    )


MINIMAL_CADDY = """\
# Generated by scripts/render-config.py (deploy/caddy/Caddyfile.example not found).
{{
\temail {email}
}}

{host} {{
\tencode zstd gzip
\treverse_proxy public:{port}
}}
"""


def render_caddy(cfg: dict, template: Path) -> Artifact:
    host = cfg["domain"]["public_host"]
    email = cfg["domain"]["acme_email"]
    if template.is_file():
        content = (
            template.read_text(encoding="utf-8")
            .replace("{$WASHBURN_PUBLIC_HOST}", host)
            .replace("{$WASHBURN_ACME_EMAIL}", email)
        )
    else:
        port = cfg["web"]["public_bind"].rsplit(":", 1)[-1]
        content = MINIMAL_CADDY.format(host=host, email=email, port=port)
    return Artifact("deploy/caddy/Caddyfile", content, "text")


def render_borg(cfg: dict) -> Artifact:
    hetzner, pg = cfg["hetzner"], cfg["postgres"]
    port = hetzner["storage_box_port"]
    repo = (
        f"ssh://{hetzner['storage_box_user']}@{hetzner['storage_box_host']}"
        f":{port}/{hetzner['repo_path']}"
    )
    entries = [
        Entry("BORG_REPO", repo),
        Entry("BORG_PASSPHRASE", hetzner["borg_passphrase"], True),
        Entry(
            "BORG_RSH",
            f"ssh -i /opt/washburn/backup/id_ed25519 -p {port} "
            "-o StrictHostKeyChecking=accept-new",
        ),
        Entry("WASHBURN_PG_CONTAINER", PG_CONTAINER),
        Entry("WASHBURN_PG_DB", pg["db"]),
        Entry("WASHBURN_PG_USER", pg["user"]),
        Entry("KEEP_DAILY", hetzner["keep_daily"]),
        Entry("KEEP_WEEKLY", hetzner["keep_weekly"]),
        Entry("KEEP_MONTHLY", hetzner["keep_monthly"]),
    ]
    # WASHBURN_BACKUP_SCHEDULE is not here: deploy.sh reads it from data.env.
    problems = []
    for e in entries:
        problems += _env_value_problems(e.key, str(e.value), _BORG_FORBIDDEN)
    if problems:
        raise ConfigError("; ".join(problems))
    header = [
        "Generated by scripts/render-config.py from washburn.toml. Do not edit.",
        "Quoted only when a value has spaces: sourced by bash (manual backup runs) and",
        "read by systemd EnvironmentFile. WASHBURN_PG_CONTAINER is pinned by data.yml.",
    ]
    return Artifact(
        "deploy/backup/borg.env",
        env_text(header, entries, quoted=True),
        "env",
        entries,
    )


def build_artifacts(cfg: dict) -> tuple[list[Artifact], list[str]]:
    warnings: list[str] = []
    derived = image_refs(cfg, warnings)
    artifacts = [
        render_tfvars(cfg),
        *(render_role_env(role, cfg, derived) for role in ROLES),
        *(render_role_toml(role, cfg) for role in ROLE_TOML_TABLES),
        render_caddy(cfg, CADDY_TEMPLATE),
        render_borg(cfg),
    ]
    if not CADDY_TEMPLATE.is_file():
        warnings.append("deploy/caddy/Caddyfile.example not found; wrote a minimal Caddyfile.")
    return artifacts, warnings


# ---------------------------------------------------------------- writing
def _fields(text: str, kind: str) -> dict[str, Any] | None:
    if kind == "env":
        out: dict[str, str] = {}
        for line in text.splitlines():
            if line and not line.startswith("#") and "=" in line:
                key, _, value = line.partition("=")
                out[key] = value
        return out
    if kind == "toml":
        try:
            return dict(_flatten(tomllib.loads(text)))
        except tomllib.TOMLDecodeError:
            return None
    if kind == "json":
        try:
            loaded = json.loads(text)
        except ValueError:
            return None
        return loaded if isinstance(loaded, dict) else None
    return None


def describe_changes(old_text: str, art: Artifact) -> list[str]:
    """Key names only. Values (possibly secret) are never shown."""
    old, new = _fields(old_text, art.kind), _fields(art.content, art.kind)
    if old is None or new is None:
        return [f"text changed ({len(old_text.splitlines())} -> {len(art.content.splitlines())} lines)"]
    lines = [f"+ {k}" for k in new if k not in old]
    lines += [f"- {k}" for k in old if k not in new]
    lines += [f"~ {k} (value changed; not shown)" for k in new if k in old and old[k] != new[k]]
    return lines


def write_artifact(out: Path, art: Artifact) -> tuple[str, list[str]]:
    path = out / art.rel
    old = path.read_text(encoding="utf-8") if path.is_file() else None
    if old is None:
        status, changes = "new", []
    elif old == art.content:
        status, changes = "unchanged", []
    else:
        status, changes = "updated", describe_changes(old, art)
    path.parent.mkdir(parents=True, exist_ok=True)
    mode = 0o600 if art.secret else 0o644
    tmp = path.with_name(f".{path.name}.tmp")
    fd = os.open(tmp, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, mode)
    with os.fdopen(fd, "w", encoding="utf-8") as fh:
        fh.write(art.content)
    os.chmod(tmp, mode)  # umask must not widen or narrow the mode
    os.replace(tmp, path)
    return status, changes


def print_summary(out: Path, results: list[tuple[Artifact, str, list[str]]]) -> None:
    print(f"Rendered {len(results)} files into {out.resolve()}")
    for art, status, changes in results:
        mode = "0600" if art.secret else "0644"
        print()
        print(f"{art.rel}  [{status}, mode {mode}]")
        if art.kind == "text":
            print(f"    text, {len(art.content.splitlines())} lines, no secrets")
        else:
            width = max((len(e.key) for e in art.entries), default=0)
            for e in art.entries:
                print(f"    {e.key:<{width}}  {e.display()}")
        for change in changes:
            print(f"    changed: {change}")
    print()
    print("washburn.toml is NOT rendered or copied. Each VM gets only its config/<role>.toml.")


# ---------------------------------------------------------------- main
def parse_args(argv: list[str] | None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Render washburn.toml into deploy artifacts.")
    parser.add_argument("--config", default="washburn.toml", help="path to washburn.toml")
    parser.add_argument("--out", default=".rendered", help="output directory")
    parser.add_argument(
        "--allow-placeholders",
        action="store_true",
        help="accept REPLACE values (used by tests only)",
    )
    return parser.parse_args(argv)


def main(argv: list[str] | None = None) -> int:
    args = parse_args(argv)
    config_path = Path(args.config)
    if not config_path.is_file():
        print(
            f"error: {config_path} not found. Copy washburn.example.toml to "
            "washburn.toml and fill in every REPLACE value.",
            file=sys.stderr,
        )
        return 2
    if not EXAMPLE_CONFIG.is_file():
        print(f"error: {EXAMPLE_CONFIG} is missing; it defines the config contract.", file=sys.stderr)
        return 2
    try:
        cfg = tomllib.loads(config_path.read_text(encoding="utf-8"))
    except tomllib.TOMLDecodeError as exc:
        print(f"error: {config_path} is not valid TOML: {exc}", file=sys.stderr)
        return 1
    example = tomllib.loads(EXAMPLE_CONFIG.read_text(encoding="utf-8"))

    errors = validate(example, cfg, allow_placeholders=args.allow_placeholders)
    if errors:
        for err in errors:
            print(f"error: {err}", file=sys.stderr)
        print(f"{len(errors)} problem(s); nothing written.", file=sys.stderr)
        return 1

    try:
        artifacts, warnings = build_artifacts(cfg)
    except ConfigError as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 1

    out = Path(args.out)
    results = []
    for art in artifacts:
        status, changes = write_artifact(out, art)
        results.append((art, status, changes))
    print_summary(out, results)
    for warning in warnings:
        print(f"warning: {warning}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
